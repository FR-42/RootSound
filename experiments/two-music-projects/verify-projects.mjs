import { readFile, writeFile } from 'node:fs/promises';
import assert from 'node:assert/strict';
import { openMusicDocument } from '../../src/workstation/app/music-document.ts';
import { createMaterialLibrary } from '../../src/workstation/modules/materials/public.ts';
import { createTimbrePlayback, createTimbreReferenceAdapter } from '../../src/workstation/modules/timbre/public.ts';
import { createPhraseEditor, createPhrasePlayback, createPhraseReferenceAdapter } from '../../src/workstation/modules/phrase/public.ts';
import { createSongEditor, createSongReferenceAdapter } from '../../src/workstation/modules/song/public.ts';
import { createSampleAudio, createBrowserSampleDecoder, createSampleReferenceAdapter } from '../../src/workstation/modules/sampling/public.ts';
import { createSampleBankAudio } from '../../src/workstation/modules/timbre/sample-bank.ts';
import { parseMidi } from '../../src/workstation/modules/midi-import/public.ts';

// Reopen only the two files generated by this experiment, with network and
// installed-bank access disabled. This is not a user-library stress test.
const results = JSON.parse(await readFile(new URL('./results.json', import.meta.url), 'utf8'));
const report = [];
for (let index = 0; index < results.length; index++) {
  const expected = results[index];
  const envelope = JSON.parse(await readFile(expected.destination, 'utf8'));
  assert.equal(envelope.format, 'RootSoundWorkspace');
  let text = envelope.libraryText;
  const library = createMaterialLibrary({ read: () => text, write: next => { text = next; } }, {
    project: { rootKind: 'rootsound.song', adapters: [createTimbreReferenceAdapter(),
      createPhraseReferenceAdapter(), createSongReferenceAdapter(), createSampleReferenceAdapter()] },
  });
  const samples = createSampleAudio(library, createBrowserSampleDecoder());
  const bank = createSampleBankAudio(library, samples, async () => { throw new Error('External assets forbidden in portable reopen'); });
  const tones = createTimbrePlayback(library, samples, undefined, bank);
  const score = createPhraseEditor(library, tones);
  const song = createSongEditor(library, createPhrasePlayback(library, tones), { defaultTempoMode: 'source' });
  openMusicDocument(library, song, score);
  const body = score.read().body;
  assert.equal(body.parts.length, expected.parts.length);
  assert.equal(body.parts.reduce((sum, part) => sum + part.notes.length, 0), expected.notes);
  const midi = parseMidi(new Uint8Array(await readFile(new URL(index === 0 ? './v3-author.mid' : './mitsuha-github.mid', import.meta.url))));
  for (let partIndex = 0; partIndex < 2; partIndex++) {
    const source = midi.notes.filter(note => note.trackIndex === partIndex + (index === 0 ? 1 : 0));
    const actual = body.parts[partIndex].notes;
    assert.equal(actual.length, source.length);
    for (let n = 0; n < source.length; n++) {
      assert(Math.abs(actual[n].startBeat * 60 / body.tempoBpm - source[n].startSeconds) < 1e-8);
      assert(Math.abs(actual[n].durationSeconds - (source[n].endSeconds - source[n].startSeconds)) < 1e-8);
      assert(Math.abs(69 + 12 * Math.log2(actual[n].frequencyHz / 440) - source[n].pitch) < 1e-8);
    }
  }
  await score.preparePreview();
  const plan = score.previewPlan();
  assert.equal(plan.events.length, expected.notes);
  assert(plan.events.every(event => event.sound.kind === 'sample' && event.sound.source.audio.channels[0]?.length > 0));
  report.push({ destination: expected.destination, reopened: true, embeddedAudioOnly: true,
    editableParts: body.parts.length, sampleEvents: plan.events.length, sourcePitchesOnsetsAndHoldsPreserved: true,
    actualDevicePlayback: false });
}
await writeFile(new URL('./verification.json', import.meta.url), JSON.stringify(report, null, 2));
console.log(JSON.stringify(report, null, 2));
